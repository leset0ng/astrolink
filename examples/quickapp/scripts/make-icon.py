"""Generate the authored app icon with only the Python standard library."""
from pathlib import Path
import struct
import zlib

SIZE = 192
SCALE = 3
DESCRIPTION = "Authored Astrolink icon: two white link endpoints joined by a blue radio bridge on OLED black. Generated by scripts/make-icon.py; no sourced or AI-generated imagery."

def color(x, y):
    # Crisp geometric link symbol, supersampled for launcher-sized output.
    bridge = 53 <= x <= 139 and abs(y - 96) <= 9
    left = (x - 53) ** 2 + (y - 96) ** 2
    right = (x - 139) ** 2 + (y - 96) ** 2
    if left <= 20 ** 2 or right <= 20 ** 2:
        return (239, 246, 255)
    if left <= 33 ** 2 or right <= 33 ** 2 or bridge:
        return (81, 138, 205)
    return (0, 0, 0)

rows = bytearray()
for y in range(SIZE):
    rows.append(0)
    for x in range(SIZE):
        samples = [color(x + (i + .5) / SCALE, y + (j + .5) / SCALE)
                   for j in range(SCALE) for i in range(SCALE)]
        rows.extend(round(sum(p[c] for p in samples) / len(samples)) for c in range(3))

def chunk(kind, data):
    return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))

output = Path(__file__).resolve().parent.parent / "src/common/icon.png"
output.write_bytes(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", SIZE, SIZE, 8, 2, 0, 0, 0)) +
                   chunk(b"tEXt", b"Source\0" + DESCRIPTION.encode()) + chunk(b"IDAT", zlib.compress(rows, 9)) + chunk(b"IEND", b""))
print(output)
